package com.alefinot.dashboardpp.ui.components

import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.graphics.vector.group
import androidx.compose.ui.unit.dp
import com.alefinot.dashboardpp.ui.theme.HudColors

/**
 * The bar's icon set, drawn rather than written.
 *
 * The app is built for a windscreen, and the menu it replaces was legible because
 * the words were long enough to read at a glance ("LIVE", "ESP SETTINGS"). Shortened
 * to a bottom bar, the same names have to survive as glyphs, so they are drawn on
 * the same 24-unit grid, with the same 1.9-unit round stroke, in the page's own
 * accent colour - no third-party icon set, because nothing else in the app carries
 * one and a borrowed shape would be a new visual language on top of an existing one.
 *
 * One icon is not drawn here at all: the live view's icon is the launcher mark
 * itself (see [Gauge]), so the app's own face is the thing the user taps to get back
 * to the driving screen.
 *
 * All of them are plain path data, not bitmaps, so the accent follows the theme and
 * the edge stays clean when the bar is scaled up on a 2560x1600 screen - and none of
 * them costs a decode at startup, which matters on a device that is also holding a
 * WebView.
 */
object HudIcons {

    /** The grid every glyph is drawn on, matching the CSS icons' 24x24 box. */
    private const val VB = 24f

    /** Stroke weight shared by the four drawn glyphs. */
    private const val W = 1.9f

    /**
     * Live: the launcher mark itself - dial, redline, needle, hub.
     *
     * The path data is copied verbatim from `res/drawable/ic_launcher_foreground.xml`
     * (generated by `scripts/preview_icon.py`, variant "gauge", and not hand-edited),
     * which draws the mark in a 108-unit safe zone; the mark occupies about 59.6 x 54.05
     * of it, centred at (59.6, 54.05). One group maps that canvas into this 24-unit
     * box: a vector group transforms its children as `p' = (p - pivot) * scale + pivot
     * + translation`, so scale 0.32 about pivot (0, 0) plus the translation below
     * centres the mark and makes it roughly 19 x 17 units. The launcher's 8.5-unit
     * stroke scales with it and lands at 2.72, so the mark stays heavier than the
     * other four glyphs - which is the point: it is the app's own icon, not a sibling
     * of them.
     *
     * If the launcher mark changes, change it here too (the two files reference each
     * other for that reason).
     */
    val Gauge: ImageVector by lazy {
        val dial = "M34.47,72.89 A25.5,25.5 0 1 1 78.74,62.67"
        val redline = "M78.74,62.67 A25.5,25.5 0 0 1 73.53,72.89"
        val needle = "M66.86,41.18 L51.40,54.31 L50.53,60.64 L56.60,58.69 Z"
        val hub = "M54.00,49.50 A7.0,7.0 0 1 1 54.00,63.50 A7.0,7.0 0 1 1 54.00,49.50 Z"
        val pivot = "M54.00,54.00 A2.5,2.5 0 1 1 54.00,59.00 A2.5,2.5 0 1 1 54.00,54.00 Z"
        ImageVector.Builder(
            name = "HudGauge", defaultWidth = VB.dp, defaultHeight = VB.dp,
            viewportWidth = VB, viewportHeight = VB,
        ).group(
            pivotX = 0f, pivotY = 0f, scaleX = 0.32f, scaleY = 0.32f,
            translationX = 12f - 59.6f * 0.32f,
            translationY = 12f - 54.05f * 0.32f,
        ) {
            // Dial, the long way round: `hud_cyan` in the launcher.
            addPath(
                PathParser().parsePathString(dial).toNodes(),
                stroke = SolidColor(HudColors.Cyan), strokeLineWidth = 8.5f,
                strokeLineCap = StrokeCap.Round,
            )
            // The redline that closes it: `hud_red`.
            addPath(
                PathParser().parsePathString(redline).toNodes(),
                stroke = SolidColor(HudColors.Red), strokeLineWidth = 8.5f,
                strokeLineCap = StrokeCap.Round,
            )
            // Needle and the hub it pivots on: `hud_amber`.
            addPath(PathParser().parsePathString(needle).toNodes(), fill = SolidColor(HudColors.Amber))
            addPath(PathParser().parsePathString(hub).toNodes(), fill = SolidColor(HudColors.Amber))
            // The pivot hole. On the launcher it is the background showing through;
            // in the bar it sits on a glass sheet, so it reads as a small dark dot.
            addPath(PathParser().parsePathString(pivot).toNodes(), fill = SolidColor(HudColors.Bg))
        }.build()
    }

    /**
     * Trips: a map pin.
     *
     * Trips are pins in every other part of this app - the map draws them, the list
     * draws them, the card draws them - so the menu uses the same mark, and it is a
     * solid shape because everywhere else it is one. The circle is the pin's bore
     * (the map's `bore: fill: var(--bg)`); the hole is cut by a second subpath wound
     * the other way, so the glass sheet behind it shows through rather than being
     * painted over.
     */
    val Pin: ImageVector by lazy {
        ImageVector.Builder(
            name = "HudPin", defaultWidth = VB.dp, defaultHeight = VB.dp,
            viewportWidth = VB, viewportHeight = VB,
        ).addPath(
            PathParser().parsePathString(
                // Teardrop (clockwise) with a circle inside it (counter-clockwise).
                "M12,2.6 C8.4,2.6 5.5,5.5 5.5,9.1 C5.5,13.6 10.2,18.9 12,21.0 " +
                    "C13.8,18.9 18.5,13.6 18.5,9.1 C18.5,5.5 15.6,2.6 12,2.6 Z " +
                    "M12,11.9 A2.8,2.8 0 1 1 12,6.3 A2.8,2.8 0 1 1 12,11.9 Z",
            ).toNodes(),
            fill = SolidColor(HudColors.Cyan),
        ).build()
    }

    /**
     * ESP settings: the chip.
     *
     * `--chip-green`, and pinned by the user: "the ESP32 as icon" (plan §3.3). The
     * body is drawn as a filled ring rather than a stroked square so the inner
     * corner stays sharp the way the CSS box is (2px outer, 2px ink inside); the
     * pins are separate strokes, 2 units out of 24 - at the bar's 22 dp they are
     * about 8 real pixels wide, which is what keeps them from going mushy on a
     * 2560x1600 screen.
     */
    val Chip: ImageVector by lazy {
        ImageVector.Builder(
            name = "HudChip", defaultWidth = VB.dp, defaultHeight = VB.dp,
            viewportWidth = VB, viewportHeight = VB,
        ).addPath(
            // Body: an 11.2-unit square ring, outer 4.4..19.6, ink 7.0..17.0, the
            // two subpaths wound opposite so the middle is empty.
            PathParser().parsePathString(
                "M6.1,4.4 H17.9 A1.7,1.7 0 0 1 19.6,6.1 V17.9 A1.7,1.7 0 0 1 17.9,19.6 " +
                    "H6.1 A1.7,1.7 0 0 1 4.4,17.9 V6.1 A1.7,1.7 0 0 1 6.1,4.4 Z " +
                    "M7.0,7.0 V17.0 H17.0 V7.0 Z",
            ).toNodes(),
            fill = SolidColor(HudColors.Cyan),
        ).apply {
            // Pins, top and bottom.
            for (x in listOf(7.6f, 12.0f, 16.4f)) {
                addPath(
                    PathParser().parsePathString("M$x,2.3 L$x,4.4 M$x,19.6 L$x,21.7").toNodes(),
                    stroke = SolidColor(HudColors.Cyan), strokeLineWidth = W,
                    strokeLineCap = StrokeCap.Round,
                )
            }
            // Pins, left and right.
            for (y in listOf(7.6f, 12.0f, 16.4f)) {
                addPath(
                    PathParser().parsePathString("M2.3,$y L4.4,$y M19.6,$y L21.7,$y").toNodes(),
                    stroke = SolidColor(HudColors.Cyan), strokeLineWidth = W,
                    strokeLineCap = StrokeCap.Round,
                )
            }
        }.build()
    }

    /**
     * App settings: the cog.
     *
     * Same geometry as the gear in `scripts/preview_icon.py` (variant "both"), which
     * is what drew the settings glyph in the bar's own mock-up: a filled 10.4-unit
     * ring with eight teeth, and a 3.4-unit bore. Filled rather than outlined
     * because an outlined cog at 22 dp loses its teeth.
     */
    val Cog: ImageVector by lazy {
        val teeth = (0 until 8).joinToString(" ") { i ->
            val a = Math.toRadians(i * 45.0)
            val nx = 12.0 + 8.4 * Math.cos(a)
            val ny = 12.0 + 8.4 * Math.sin(a)
            val bx = 12.0 + 5.4 * Math.cos(a)
            val by = 12.0 + 5.4 * Math.sin(a)
            "M%.2f,%.2f L%.2f,%.2f".format(bx, by, nx, ny)
        }
        ImageVector.Builder(
            name = "HudCog", defaultWidth = VB.dp, defaultHeight = VB.dp,
            viewportWidth = VB, viewportHeight = VB,
        ).addPath(
            // Ring: outer r 6.7 (wound clockwise), bore r 3.4 (wound the other way).
            PathParser().parsePathString(
                "M12,5.3 A6.7,6.7 0 1 1 12,18.7 A6.7,6.7 0 1 1 12,5.3 Z " +
                    "M12,8.6 A3.4,3.4 0 1 0 12,15.4 A3.4,3.4 0 1 0 12,8.6 Z",
            ).toNodes(),
            fill = SolidColor(HudColors.Cyan),
        ).addPath(
            PathParser().parsePathString(teeth).toNodes(),
            stroke = SolidColor(HudColors.Cyan), strokeLineWidth = 2.4f,
            strokeLineCap = StrokeCap.Round,
        ).build()
    }

    /**
     * Coming Soon: a clock with the hour hand pointing at twelve - "not open yet".
     *
     * Kept quiet (dim, not accented) because it is an advertisement for a screen that
     * does not exist, not a destination: tapping it never changes the page.
     */
    val Clock: ImageVector by lazy {
        ImageVector.Builder(
            name = "HudClock", defaultWidth = VB.dp, defaultHeight = VB.dp,
            viewportWidth = VB, viewportHeight = VB,
        ).addPath(
            PathParser().parsePathString("M12,12 A9.1,9.1 0 1 1 12,11.99 Z").toNodes(),
            stroke = SolidColor(HudColors.Cyan), strokeLineWidth = W,
        ).addPath(
            PathParser().parsePathString("M12,12.9 L12,6.6 M12,12.9 L16.4,14.6").toNodes(),
            stroke = SolidColor(HudColors.Cyan), strokeLineWidth = W,
            strokeLineCap = StrokeCap.Round,
        ).build()
    }
}
