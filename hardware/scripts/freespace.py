"""Local helper: can a Ø10-class cylindrical can fit here, and where?

Prints the free rectangles that would take a cylindrical SMD electrolytic big
enough to need an 11.0 x 13.3 mm courtyard (Capacitor_SMD:CP_Elec_10x12.5
standing at rot 90/270 - its courtyard is 13.3 x 11.0 at rot 0).  Courtyards
are inflated by 0.25 mm and the current placement is taken from make_pcb.py,
so the answer follows the board as generated.

This is how the 10 mm west extension was justified (plan: "carrier stage 3 -
board extension 95x55, bulk caps to B.Cu"): inside the drawn 85 x 55 envelope
the only such void is the mid SMD strip, ~50 mm from the power section and
underneath the DevKit body.

    python scripts/freespace.py                 # current outline
    python scripts/freespace.py --drawn         # drawn 85 x 55 envelope
    python scripts/freespace.py --ignore C1 C3  # pretend those parts are gone

Not part of the build; the board is generated by make_pcb.py.
"""
import sys
sys.path.insert(0, ".")
import make_pcb as m

CLR = 0.25
IGNORE = set()
DRAWN = False
args = sys.argv[1:]
i = 0
while i < len(args):
    if args[i] == "--ignore":
        i += 1
        while i < len(args) and not args[i].startswith("--"):
            IGNORE.add(args[i])
            i += 1
        continue
    if args[i] == "--drawn":
        DRAWN = True
    i += 1

boxes = []
for e in m.parts():
    bb = m.box_of(e)
    if bb and e[0] not in IGNORE:
        boxes.append((e[0],) + tuple(bb))

X0, X1 = (10.0, m.BOARD_X1) if DRAWN else (m.BOARD_X0, m.BOARD_X1)
Y0, Y1 = m.BOARD_Y0, m.BOARD_Y1


def blocked(x, y, w, h):
    """First courtyard that a W x H box at (x, y) would hit, or None."""
    for ref, bx0, by0, bx1, by1 in boxes:
        if not (x >= bx1 + CLR or x + w <= bx0 - CLR
                or y >= by1 + CLR or y + h <= by0 - CLR):
            return ref
    return None


print("outline x %.2f..%.2f  y %.2f..%.2f  (%.0f x %.0f mm)%s"
      % (X0, X1, Y0, Y1, X1 - X0, Y1 - Y0,
         "  [drawn envelope]" if DRAWN else ""))
for W, H in ((11.0, 13.3), (13.3, 11.0)):
    xs = [X0 + CLR + k * 0.5 for k in range(int((X1 - X0 - 2 * CLR - W) / 0.5) + 1)]
    ys = [Y0 + CLR + k * 0.5 for k in range(int((Y1 - Y0 - 2 * CLR - H) / 0.5) + 1)]
    free = [(x, y) for x in xs for y in ys if not blocked(x, y, W, H)]
    if not free:
        print("  %.1f x %.1f mm: no room" % (W, H))
        continue
    from collections import defaultdict
    byx = defaultdict(list)
    for x, y in free:
        byx[round(x)].append(y)
    keys = sorted(byx)
    runs, cur = [], [keys[0]]
    for a, b in zip(keys, keys[1:]):
        if b - a <= 1:
            cur.append(b)
        else:
            runs.append((cur[0], cur[-1]))
            cur = [b]
    runs.append((cur[0], cur[-1]))
    for lo, hi in runs:
        yy = [y for k in byx if lo <= k <= hi for y in byx[k]]
        print("  %.1f x %.1f mm: can centre x %.2f..%.2f, y %.2f..%.2f"
              % (W, H, lo + W / 2, hi + W / 2, min(yy) + H / 2, max(yy) + H / 2))
